const solutionCardLookup = solutionsCards.reduce((lookup, card) => {
	const slug = card.url?.split("/").filter(Boolean).pop();

	if (slug) {
		lookup[slug] = card;
	}

	return lookup;
}, {});

const getFallbackRelatedSlugs = slug => {
	const group = solutionCategoryGroups.find(items => items.includes(slug));

	return group?.filter(item => item !== slug).slice(0, 3) || [];
};

const makeRelatedSolutionCard = slug => {
	const detail = solutionPages[slug];

	if (!detail) {
		return null;
	}

	const card = solutionCardLookup[slug];

	return {
		title: card?.title || detail.relatedTitle || detail.kicker,
		desc: card?.desc || detail.relatedDesc || detail.desc,
		icon: card?.icon || detail.relatedIcon || "tji-service-4",
		url: `/solutions/${slug}`,
	};
};

export const getRelatedSolutions = slug => {
	const preferredSlugs = relatedSolutionSlugs[slug] || getFallbackRelatedSlugs(slug);
	const related = preferredSlugs
		.map(makeRelatedSolutionCard)
		.filter(Boolean)
		.slice(0, 3);

	if (related.length) {
		return related;
	}

	return solutionsCards
		.filter(solution => !solution.url.endsWith(`/${slug}`))
		.slice(0, 3);
};
